export const pick = <T>(items: readonly T[]): T => items[Math.floor(Math.random() * items.length)]!

export const randomPhone = (): string => `+7999${String(Math.floor(Math.random() * 10_000_000)).padStart(7, '0')}`

export const randomPerson = (): { firstName: string; lastName: string; fullName: string } => {
  const [firstName, lastName] = Math.random() < 0.5 ? pick(FEMALE) : pick(MALE)
  return { firstName, lastName, fullName: `${firstName} ${lastName}` }
}
